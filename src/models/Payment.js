const mongoose = require('mongoose');

// One row per Mobile Money / card payment attempt, whether it's a student's
// admission-fee deposit or a shopper paying for a product directly. Eric:
// "Students must pay their fees through Momo on 0209317581" and then "Let
// students enter their phone number and the money will be deducted from
// their account" — actually pulling money out of a MoMo wallet needs a
// licensed payment aggregator in the middle (you can't debit a phone number
// from custom code), so this is built on Paystack (see utils/paystack.js),
// which supports MTN/Vodafone/AirtelTigo Mobile Money for Ghana. The
// student's own phone-number entry happens on Paystack's own secure
// checkout page, never on this site — this project never touches a MoMo PIN
// or OTP directly, only the pass/fail result of the whole transaction.
const paymentSchema = new mongoose.Schema(
  {
    type: { type: String, enum: ['admission_fee', 'shop_order'], required: true },
    // Paystack transaction reference — generated by us before calling
    // Paystack, unique so re-initializing never collides with a past attempt.
    reference: { type: String, required: true, unique: true },
    amount: { type: Number, required: true }, // GHS, main unit (not pesewas)
    currency: { type: String, default: 'GHS' },
    status: {
      type: String,
      enum: ['pending', 'success', 'failed', 'abandoned'],
      default: 'pending',
    },
    email: { type: String, required: true },
    phone: { type: String },
    name: { type: String },
    // Set only for type: 'admission_fee'.
    application: { type: mongoose.Schema.Types.ObjectId, ref: 'Application' },
    // Set only for type: 'shop_order'.
    galleryItem: { type: mongoose.Schema.Types.ObjectId, ref: 'Gallery' },
    gatewayResponse: { type: String }, // Paystack's human-readable result, e.g. "Approved"
    paidAt: { type: Date },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Payment', paymentSchema);
